    private void btnConnectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConnectActionPerformed
        try {
    String ip = txtIP.getText().trim();
    int port = Integer.parseInt(txtPort.getText().trim());
    String nick = txtNick.getText().trim();
    if (nick.isEmpty()) { javax.swing.JOptionPane.showMessageDialog(this, "Enter nickname"); return; }
    socket = new Socket(ip, port);
    out = new PrintWriter(socket.getOutputStream(), true);
    in = new BufferedReader(new java.io.InputStreamReader(socket.getInputStream()));
    out.println(nick);
    txtChat.append("Connected as " + nick + "\n");
    btnConnect.setEnabled(false);
    listenThread = new Thread(() -> {
        try {
            String line;
            while ((line = in.readLine()) != null) {
                String msg = line;
                javax.swing.SwingUtilities.invokeLater(() -> txtChat.append(msg + "\n"));
            }
        } catch (java.io.IOException e) {}
    });
    listenThread.start();
} catch (Exception e) {
    javax.swing.JOptionPane.showMessageDialog(this, "Cannot connect: " + e.getMessage());
}




    }//GEN-LAST:event_btnConnectActionPerformed

    private void btnDisconnectActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDisconnectActionPerformed
        try {
    if (out != null) out.println("LEAVE");
    if (socket != null) socket.close();
    txtChat.append("Disconnected\n");
    btnConnect.setEnabled(true);
} catch (Exception e) {}

    }//GEN-LAST:event_btnDisconnectActionPerformed

